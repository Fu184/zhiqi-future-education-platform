-- 智启未来：H2 建表脚本；Spring Boot 启动时自动执行。
-- 导出交付文件：backend/sql/schema-h2.sql，需与本文件同步。
-- 时间戳以数据库时间保存；会话和验证码过期时间为毫秒级 Unix 时间。
-- 普通 ordinary、可学习 learner、校长 principal、老师 teacher、管理员 admin、政府 government。

-- 用户、上下级归属和创建配额；密码由 Java 使用 BCrypt 编码，不写入明文初始化密码。
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(11) NOT NULL UNIQUE,
    name VARCHAR(40) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ordinary','learner','principal','teacher','admin','government')),
    parent_id BIGINT REFERENCES users(id),
    teacher_quota INT NOT NULL DEFAULT 0 CHECK (teacher_quota >= 0),
    student_quota INT NOT NULL DEFAULT 0 CHECK (student_quota >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- 登录会话：仅保存随机令牌的 SHA-256 摘要。
CREATE TABLE IF NOT EXISTS sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    expires_at BIGINT NOT NULL
);
-- 短信验证码：仅保存 HMAC 摘要，以及发送时间和错误尝试次数。
CREATE TABLE IF NOT EXISTS sms_codes (
    phone VARCHAR(11) PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL,
    expires_at BIGINT NOT NULL,
    sent_at BIGINT NOT NULL,
    attempts INT NOT NULL DEFAULT 0
);
-- 短信、登录和修改密码的请求频率限制。
CREATE TABLE IF NOT EXISTS rate_limits (
    rate_key VARCHAR(200) PRIMARY KEY,
    request_count INT NOT NULL,
    reset_at BIGINT NOT NULL
);
-- 管理员核实的购买凭证；编号全局唯一，记录购买用户及确认人。
CREATE TABLE IF NOT EXISTS purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    purchase_reference VARCHAR(100) NOT NULL UNIQUE,
    confirmed_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- 注册、创建账号、管理资料、确认购买和改密码的审计记录。
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id),
    action VARCHAR(50) NOT NULL,
    target_id BIGINT REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS users_parent ON users(parent_id);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
-- 事务内按机构根账号、手机号和限流键分别加锁；不同机构互不阻塞。
CREATE TABLE IF NOT EXISTS operation_locks (lock_key VARCHAR(240) PRIMARY KEY);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
